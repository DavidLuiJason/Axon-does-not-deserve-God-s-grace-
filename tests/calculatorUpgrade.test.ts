let checks = 0;
function assert(ok: boolean, message: string): void { checks++; if (!ok) throw new Error(`FAIL: ${message}`); }
function near(a: number, b: number, epsilon = 1e-11): boolean { return Math.abs(a - b) <= epsilon * Math.max(1, Math.abs(b)); }
function good(expression: string, expected: number, angle: 'deg'|'rad' = 'deg', ans?: number): void {
  const result = evaluate(expression, { angle, ...(ans === undefined ? {} : { ans }) });
  assert(result.ok && near(result.value, expected), `${expression} => ${expected}; got ${JSON.stringify(result)}`);
}
function bad(expression: string, code: string, hintPart: string, angle: 'deg'|'rad' = 'deg'): void {
  const result = evaluate(expression, { angle });
  assert(result.ok === false && result.error === code && result.hint.toLowerCase().includes(hintPart.toLowerCase()) && Number.isInteger(result.position) && typeof result.interpreted === 'string', `${expression} error contract; got ${JSON.stringify(result)}`);
}
