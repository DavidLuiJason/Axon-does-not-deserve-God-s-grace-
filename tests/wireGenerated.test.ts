import { readFile, mkdtemp, mkdir, writeFile, cp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { addOnlyList, addOnlyRecord, addOnlyRows, GENERATED_CLASHES } from '../src/generated/mergeGenerated';
import { CATALOG_TOOLS } from '../src/tools/toolCatalog';
import { LEGACY_ENGINE_DESCRIPTORS } from '../src/tools/engines/legacyDescriptors';
import { ACTION_SCHEMAS } from '../src/brain/mind/schema/actionSchemas';
import { SLOT_DEFAULTS } from '../src/brain/mind/bind/bindDefaults';
import { LIVE_SWITCHES, LIVE_CHOICES, LIVE_TASKS } from '../src/tools/runners/liveSwitches';
import { registerAxonToolsCapability } from '../src/capabilities/registerAxonTools';

let checks = 0;
function check(condition: unknown, label: string): void {
  checks += 1;
  if (!condition) throw new Error(`FAIL ${label}`);
}
const toolPath = '../tools/wire.mjs';
const wire: any = await import(toolPath);
const root = '.';

// 1. STALE CHECK: the committed src/generated files are exactly what the cards produce now.
const pl = wire.plan(root);
check(pl.skipped.length === 0, 'no card is skipped');
check(pl.refused.length === 0, 'no card part is refused');
const files = wire.render(pl);
check(wire.GENERATED_FILES.length === 6, 'six generated files are expected');
for (const name of wire.GENERATED_FILES) {
  const committed = await readFile(`./src/generated/${name}`, 'utf8');
  check(committed === files[name], `src/generated/${name} is not stale (run: node tools/wire-write.mjs)`);
  check(committed.startsWith('// GENERATED by tools/wire-write.mjs'), `${name} carries the do-not-edit header`);
}
check(JSON.stringify(wire.render(wire.plan(root))) === JSON.stringify(files), 'rendering twice gives the same bytes');

// 2. The real registries load with NO clash between hand wiring and generated wiring.
registerAxonToolsCapability();
check(GENERATED_CLASHES.length === 0, `no hand/generated clash (${GENERATED_CLASHES.join('; ')})`);
check(CATALOG_TOOLS.some((t) => t.id === 'sort-lines'), 'the hand catalog entry for Sort Lines is still there');
check(LEGACY_ENGINE_DESCRIPTORS.some((d) => d.toolId === 'sort-lines'), 'the hand descriptor for Sort Lines is still there');
check(ACTION_SCHEMAS.some((s) => s.tool === 'sort-lines'), 'the hand schema row for Sort Lines is still there');
check(SLOT_DEFAULTS['sort-lines']?.mode?.value === 'ascending', 'the hand bind default for Sort Lines is still there');
check(LIVE_SWITCHES['sort-lines'] === 'runner' && LIVE_SWITCHES['text-counter'] === 'runner' && LIVE_SWITCHES['case-converter'] === 'runner', 'the three live switches are unchanged');
check(Object.keys(LIVE_CHOICES).sort().join() === 'case-converter,encoder-decoder,hash-tool,qr-maker,sort-lines,text-counter', 'the live choice sets are the three earlier ones plus encoder-decoder, hash-tool and qr-maker (CONNECT2)');
check(Object.keys(LIVE_TASKS).sort().join() === 'case-converter,encoder-decoder,hash-tool,number-to-words,qr-maker,sort-lines,text-counter', 'the live tasks are the three earlier ones plus number-to-words, encoder-decoder, hash-tool and qr-maker (CONNECT2)');

// 3. Merge rules (own sink, so the global list stays clean): add new, hand wins, clash is recorded.
{
  const sink: string[] = [];
  const merged = addOnlyList([{ id: 'a', v: 1 }, { id: 'b', v: 2 }], [{ id: 'b', v: 9 }, { id: 'c', v: 3 }, { id: 'c', v: 4 }], (x) => x.id, 'list', sink);
  check(merged.map((x) => `${x.id}${x.v}`).join() === 'a1,b2,c3', 'list merge: new added, hand wins, duplicate generated dropped');
  check(sink.join() === 'list: b,list: c', 'list merge records each clash');
  const sink2: string[] = [];
  const rec = addOnlyRecord<number>({ a: 1 }, { a: 5, z: 6 }, 'record', sink2);
  check(rec.a === 1 && rec.z === 6 && sink2.join() === 'record: a', 'record merge: hand wins, new added, clash recorded');
  const sink3: string[] = [];
  const text = addOnlyRows('\nx | 1\ny | 2\n', ['y | 9', 'z | 3'], 'row', sink3);
  check(text === '\nx | 1\ny | 2\n\nz | 3' && sink3.join() === 'row: y', 'row merge: hand row wins, new row appended, clash recorded');
}

// 4. Generator rules on a throw-away copy of the repo wiring (nothing in the real repo is touched).
const tmp = await mkdtemp(join(tmpdir(), 'wire-'));
try {
  for (const f of ['src/tools/toolCatalog.ts', 'src/capabilities/registerAxonTools.ts', 'src/tools/engines/legacyDescriptors.ts', 'src/brain/mind/schema/actionSchemas.ts', 'src/brain/mind/bind/bindDefaults.ts', 'src/tools/runners/liveSwitches.ts']) {
    await mkdir(join(tmp, f, '..'), { recursive: true });
    await cp(f, join(tmp, f));
  }
  await mkdir(join(tmp, 'wiring'), { recursive: true });
  const demo = {
    wireVersion: 1, toolId: 'demo-tool', displayName: 'Demo Tool',
    catalog: { description: 'A demo.', groupId: 'text-writing', status: 'coming-soon' },
    chat: { actionId: 'act.demo-tool', purpose: 'Run the demo', examples: ['run the demo'], status: 'not-built' },
    descriptor: { const: 'DEMO_TOOL_DESCRIPTOR', purpose: 'Demo.', examples: ['Demo it.'], inputs: [{ name: 'text', kind: 'text' }, { name: 'mode', kind: 'choice', choices: ['a', 'b'] }] },
    schemaRow: ['demo-tool', 'c a', 'demo run', 'demo:n', '', 'text:text:r', 'shows-result', '', 'quick low', 'not-needed'],
    bindDefaults: { mode: { value: 'a', note: 'using a' } },
    live: null,
  };
  const put = (name: string, c: unknown) => writeFile(join(tmp, 'wiring', name), JSON.stringify(c));
  await put('demo-tool.wire.json', demo);
  const p1 = wire.plan(tmp);
  check(p1.skipped.length === 0 && p1.refused.length === 0, 'a new not-live card is accepted');
  const f1 = wire.render(p1);
  check(f1['wiredCatalog.ts'].includes("id: 'demo-tool',") && f1['wiredCatalog.ts'].includes("status: 'coming-soon',") && !f1['wiredCatalog.ts'].includes('opens:'), 'catalog entry generated without opens');
  check(f1['wiredChatActions.ts'].includes("id: 'act.demo-tool',") && f1['wiredChatActions.ts'].includes("status: 'not-built',") && !f1['wiredChatActions.ts'].includes('link:'), 'chat action generated without link');
  check(f1['wiredDescriptors.ts'].includes('export const DEMO_TOOL_DESCRIPTOR =') && f1['wiredDescriptors.ts'].includes('GENERATED_DESCRIPTORS = [DEMO_TOOL_DESCRIPTOR] as const'), 'descriptor generated and listed');
  check(f1['wiredSchemaRows.ts'].includes("'demo-tool | c a | demo run | demo:n |  | text:text:r | shows-result |  | quick low | not-needed',"), 'schema row generated in the hand format');
  check(f1['wiredBindDefaults.ts'].includes("'demo-tool': Object.freeze({ mode: { value: 'a', note: 'using a' } }),"), 'bind default generated');
  check(!f1['wiredLive.ts'].split('\n').slice(2).join('\n').includes('demo-tool'), 'a not-live card generates nothing in the live file');
  check(JSON.stringify(wire.render(wire.plan(tmp))) === JSON.stringify(f1), 'generation is deterministic');

  // a card edit changes the output, so a stale committed file would be caught
  await put('demo-tool.wire.json', { ...demo, displayName: 'Demo Tool 2' });
  check(JSON.stringify(wire.render(wire.plan(tmp))) !== JSON.stringify(f1), 'a changed card changes the generated bytes (staleness is detectable)');
  await put('demo-tool.wire.json', demo);

  // refusals and skips
  await put('clash.wire.json', { ...demo, toolId: 'text-compare', schemaRow: ['text-compare', ...demo.schemaRow.slice(1)], chat: { ...demo.chat, actionId: 'act.new-compare' }, descriptor: { ...demo.descriptor, const: 'X_DESCRIPTOR' } });
  const p2 = wire.plan(tmp);
  check(p2.refused.some((r: string) => r.includes('text-compare') && r.includes('"catalog"')), 'a part already wired by hand is refused (catalog)');
  check(p2.refused.some((r: string) => r.includes('text-compare') && r.includes('"descriptor"')), 'a part already wired by hand is refused (descriptor)');
  check(p2.refused.some((r: string) => r.includes('text-compare') && r.includes('"schema"')), 'a part already wired by hand is refused (schema)');
  check(!wire.render(p2)['wiredCatalog.ts'].includes("'text-compare'"), 'a refused card emits nothing');
  await rm(join(tmp, 'wiring', 'clash.wire.json'));
  await put('twin.wire.json', demo);
  check(wire.plan(tmp).refused.some((r: string) => r.includes('same toolId')), 'two cards with one toolId are refused');
  await rm(join(tmp, 'wiring', 'twin.wire.json'));
  const liveCard = { ...demo, live: { switch: 'runner', choicesConst: 'A_CHOICES', choiceSlot: 'mode', actionConst: 'A_ACTION' } };
  check(typeof wire.checkCard(liveCard) === 'string', 'a generated live block without approvedOn and imports is refused');
  check(wire.checkCard({ ...liveCard, live: { ...liveCard.live, approvedOn: '2026-11-04', imports: [{ from: 'tools/a', names: ['A_CHOICES', 'A_ACTION'] }] } }) === null, 'a live block with approvedOn and imports passes');
  check(typeof wire.checkCard({ ...demo, live: { ...liveCard.live, approvedOn: '2026-11-04', imports: [{ from: 'tools/a', names: ['A_CHOICES'] }] } }) === 'string', 'a live block whose constant is not imported is refused');
  check(typeof wire.checkCard({ ...demo, catalog: { ...demo.catalog, status: 'available' } }) === 'string', 'available without opens is refused');
  check(typeof wire.checkCard({ ...demo, handParts: ['everything'] }) === 'string', 'an unknown handParts name is refused');
  const liveOk = { ...liveCard, live: { ...liveCard.live, foldSlot: 'mode', foldFn: 'foldA', approvedOn: '2026-11-04', imports: [{ from: 'tools/a', names: ['A_CHOICES', 'A_ACTION', 'foldA'] }, { from: 'tools/textSortAction', names: ['X'] }] } };
  await put('demo-tool.wire.json', liveOk);
  const f2 = wire.render(wire.plan(tmp));
  check(f2['wiredLive.ts'].includes("import { A_ACTION, A_CHOICES, foldA } from '../tools/a';") && f2['wiredLive.ts'].includes("'demo-tool': 'runner' as const,") && f2['wiredLive.ts'].includes('mode: foldA(args.mode)'), 'an approved live card generates imports, switch and task');
} finally {
  await rm(tmp, { recursive: true, force: true });
}

// 5. The writer touches only src/generated and uses no clock, randomness or network; the generator itself still writes nothing.
const writer = await readFile('./tools/wire-write.mjs', 'utf8');
for (const word of ['Date.now', 'new Date', 'Math.random', 'fetch(', 'unlink', 'rmSync', 'renameSync', 'appendFile', 'child_process']) check(!writer.includes(word), `tools/wire-write.mjs does not use ${word}`);
check(writer.includes("const OUT_DIR = 'src/generated';"), 'the writer has one fixed output folder');
check((writer.match(/writeFileSync\(/g) ?? []).length === 1 && writer.includes('writeFileSync(path, files[name])'), 'the writer has exactly one write call');
check(!/'src\/(?!generated)/.test(writer), 'the writer names no other src path');
const gen = await readFile('./tools/wire.mjs', 'utf8');
for (const word of ['writeFile', 'mkdirSync', 'unlink', 'rmSync']) check(!gen.includes(word), `tools/wire.mjs does not use ${word}`);

console.log(`WIRE GENERATED OK: ${checks} checks`);
