import test from 'node:test';
import assert from 'node:assert/strict';
import {
  BrainRequestGate, MemoryBrainRequestReplayStore, ApprovedPatchService,
  WorkbenchStateManager, createDefaultWorkbenchCommandCatalogue,
  DocumentBufferManager, MemoryWorkspaceFileStore, WorkingCopyManager,
  bindWorkbenchPanels
} from '../dist/index.js';

function auth(overrides = {}) {
  return { authority: 'USER', requestId: 'req-1', intentId: 'intent-1', issuedAt: 1000,
    expiresAt: 4_000, approvalReference: 'approval-1', scopes: ['workspace:patch'], ...overrides };
}
const patchRequest = (overrides = {}) => ({ operation: 'APPLY_APPROVED_PATCH', authorisation: auth(), projectId: 'workspace-1',
  payload: { workspaceId: 'workspace-1' }, suppliedPatch: { file: 'src/main.ts', baseText: 'const x = 1;\n', startOffset: 10, endOffset: 11,
    oldText: '1', newText: '2', reason: 'User-approved literal update', safety: 'mechanical' }, ...overrides });

test('R9 workbench host profiles and initial explorer state are explicit', () => {
  const phone = new WorkbenchStateManager('PHONE');
  assert.equal(phone.snapshot().hostProfile, 'PHONE');
  assert.deepEqual(phone.snapshot().visiblePanels, ['EXPLORER']);
  assert.throws(() => new WorkbenchStateManager('UNKNOWN'), /tab limit|host/i);
});

test('R9 workbench blocks switching projects while dirty tabs exist', () => {
  const state = new WorkbenchStateManager('DESKTOP');
  state.openProject('p1'); state.openDocument('src/main.ts'); state.markDirty('src/main.ts', true);
  assert.throws(() => state.openProject('p2'), /unsaved/);
  state.openProject('p2', true);
  assert.equal(state.snapshot().projectId, 'p2');
  assert.equal(state.snapshot().tabs.length, 0);
});

test('R9 workbench validates paths, bounds tabs and tracks panel visibility', () => {
  const state = new WorkbenchStateManager('PHONE', { maxOpenTabs: 2, now: () => 42 });
  state.openProject('p');
  assert.throws(() => state.openDocument('../escape.ts'), /unsafe/);
  assert.equal(state.openDocument('a.ts').openedAt, 42);
  state.openDocument('b.ts');
  assert.throws(() => state.openDocument('c.ts'), /tab limit/);
  state.showPanel('TERMINAL');
  assert.ok(state.snapshot().visiblePanels.includes('TERMINAL'));
  state.showPanel('TERMINAL', false);
  assert.ok(!state.snapshot().visiblePanels.includes('TERMINAL'));
  assert.throws(() => state.showPanel('NOPE'), /unsupported/i);
});

test('R9 command catalogue refuses to dispatch unbound host controls', async () => {
  const registry = createDefaultWorkbenchCommandCatalogue();
  assert.equal(registry.list('RUN').every((x) => x.state === 'ADAPTER_REQUIRED'), true);
  await assert.rejects(registry.dispatch('run.project'), /not bound/);
  const state = new WorkbenchStateManager('TABLET');
  bindWorkbenchPanels(registry, state);
  const result = await registry.dispatch('view.problems');
  assert.equal(result.activePanel, 'PROBLEMS');
  assert.equal(registry.list('VIEW').find((x) => x.id === 'view.problems').state, 'BOUND');
  assert.throws(() => registry.bind('missing.command', () => null), /unknown/i);
});

test('R9 document buffers require externally supplied source and explicit save approval', async () => {
  const store = new MemoryWorkspaceFileStore();
  await store.write('w', 'main.ts', 'const n = 1;');
  const buffers = new DocumentBufferManager(store, () => 123);
  const opened = await buffers.open('w', 'main.ts');
  assert.equal(opened.dirty, false);
  assert.throws(() => buffers.supplyContent({ workspaceId: 'w', path: 'main.ts', content: 'const n = 2;', source: 'AUTOGENERATED', approvalReference: 'a' }), /only user|source/i);
  const supplied = buffers.supplyContent({ workspaceId: 'w', path: 'main.ts', content: 'const n = 2;', source: 'AXON_BRAIN', approvalReference: 'brain-request' });
  assert.equal(supplied.dirty, true);
  await assert.rejects(buffers.save('w', 'main.ts', { approved: false, approvalReference: '' }), /approval/);
  const saved = await buffers.save('w', 'main.ts', { approved: true, approvalReference: 'user-approved' });
  assert.equal(saved.dirty, false);
  assert.equal(await store.read('w', 'main.ts'), 'const n = 2;');
});

test('R9 document buffers reject stale writes and dirty discard without permission', async () => {
  const store = new MemoryWorkspaceFileStore();
  await store.write('w', 'main.ts', 'one');
  const buffers = new DocumentBufferManager(store);
  await buffers.open('w', 'main.ts');
  buffers.supplyContent({ workspaceId: 'w', path: 'main.ts', content: 'two', source: 'USER', approvalReference: 'user-input' });
  await store.write('w', 'main.ts', 'external');
  await assert.rejects(buffers.save('w', 'main.ts', { approved: true, approvalReference: 'approved' }), /stale/);
  assert.throws(() => buffers.close('w', 'main.ts', false), /unsaved/);
  buffers.discard('w', 'main.ts');
  buffers.close('w', 'main.ts', false);
});

test('R9 document buffers enforce per-document and open-document limits', async () => {
  const store = new MemoryWorkspaceFileStore();
  await store.write('w', 'a', 'a'); await store.write('w', 'b', 'b');
  const buffers = new DocumentBufferManager(store, Date.now, 1, 1);
  await buffers.open('w', 'a');
  await assert.rejects(buffers.open('w', 'b'), /buffer limit/);
  assert.throws(() => buffers.supplyContent({ workspaceId: 'w', path: 'a', content: 'two', source: 'USER', approvalReference: 'x' }), /size/);
});

test('R9 Brain request gate validates authority, project scope and request lifetime', () => {
  const gate = new BrainRequestGate({ now: () => 2000, maxLifetimeMs: 5000 });
  assert.doesNotThrow(() => gate.validate(patchRequest({ authorisation: auth({ issuedAt: 1000, expiresAt: 3000 }) }), 'workspace:patch'));
  assert.throws(() => gate.validate(patchRequest({ authorisation: auth({ expiresAt: 2000 }) }), 'workspace:patch'), /expired/);
  assert.throws(() => gate.validate(patchRequest({ authorisation: auth({ scopes: ['project:read'] }) }), 'workspace:patch'), /scope/);
  assert.throws(() => gate.validate(patchRequest({ suppliedPatch: undefined }), 'workspace:patch'), /supplied patch/);
  assert.throws(() => gate.validate(patchRequest({ authorisation: auth({ authority: 'AXON_BRAIN', userApproved: false }) }), 'workspace:patch'), /user approval/);
});

test('R9 Brain request gate rejects malformed runtime shapes and oversized supplied patches', () => {
  const gate = new BrainRequestGate({ now: () => 2000, maxLifetimeMs: 5000, maxPatchBytes: 20 });
  assert.throws(() => gate.validate(patchRequest({ projectId: 7 }), 'workspace:patch'), /project ID/i);
  assert.throws(() => gate.validate(patchRequest({ authorisation: auth({ issuedAt: 1000, expiresAt: 3000, scopes: ['workspace:patch', 'workspace:patch'] }) }), 'workspace:patch'), /malformed/i);
  assert.throws(() => gate.validate(patchRequest({ authorisation: auth({ issuedAt: 1000, expiresAt: 3000 }), suppliedPatch: { file: 'main.ts', baseText: 'x'.repeat(30), startOffset: 0, endOffset: 0, oldText: '', newText: '', reason: 'large', safety: 'mechanical' } }), 'workspace:patch'), /byte limit/i);
});

test('R9 Brain request gate prevents request replay with a claimed request ID', async () => {
  const replay = new MemoryBrainRequestReplayStore();
  const gate = new BrainRequestGate({ now: () => 2000, replayStore: replay });
  const request = patchRequest({ authorisation: auth({ issuedAt: 1000, expiresAt: 9000 }) });
  await gate.validateAndClaim(request, 'workspace:patch');
  await assert.rejects(gate.validateAndClaim(request, 'workspace:patch'), /already been used/);
});

test('R9 ApprovedPatchService applies only the exact user-supplied patch to the authorised workspace', async () => {
  const fileStore = new MemoryWorkspaceFileStore();
  const working = new WorkingCopyManager(fileStore);
  await working.create('workspace-1', { 'src/main.ts': 'const x = 1;\n' });
  const service = new ApprovedPatchService(new BrainRequestGate({ now: () => 2000 }), working);
  const result = await service.apply(patchRequest({ authorisation: auth({ issuedAt: 1000, expiresAt: 9000 }) }));
  assert.equal(result.applied, true);
  assert.equal(await fileStore.read('workspace-1', 'src/main.ts'), 'const x = 2;\n');
});

test('R9 ApprovedPatchService rejects project/workspace mismatch and stale source', async () => {
  const fileStore = new MemoryWorkspaceFileStore();
  const working = new WorkingCopyManager(fileStore);
  await working.create('workspace-1', { 'src/main.ts': 'const x = 9;\n' });
  const service = new ApprovedPatchService(new BrainRequestGate({ now: () => 2000 }), working);
  const request = patchRequest({ authorisation: auth({ issuedAt: 1000, expiresAt: 9000 }) });
  await assert.rejects(service.apply({ ...request, payload: { workspaceId: 'workspace-2' } }), /identity/);
  await assert.rejects(service.apply(request), /stale/);
});

