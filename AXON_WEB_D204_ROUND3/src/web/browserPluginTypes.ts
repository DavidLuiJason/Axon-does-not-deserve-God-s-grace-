export type NativeBrowserState = Readonly<{
  available: boolean;
  tabCount: number;
  activeIndex: number;
  url: string;
  title: string;
  loading: boolean;
  canGoBack: boolean;
  canGoForward: boolean;
  engine: string;
  incognito: false;
}>;
export type BrowserSavedItem = Readonly<{ title: string; url: string; id?: string; folder?: string; read?: boolean; visitedAt?: number; addedAt?: number }>;
export type BrowserFolder = Readonly<{ name: string }>;
export type BrowserDownloadItem = Readonly<{ id: string; title: string; status: 'RUNNING' | 'PAUSED' | 'SUCCESSFUL' | 'FAILED'; reason: number; mimeType: string | null; downloadedBytes: number; totalBytes: number; uri: string }>;
export type BrowserSecurityDetails = Readonly<{ url: string; scheme: string; host: string; certificatePresent: boolean; subject: string; issuer: string }>;
export type BrowserSitePermissionSummary = Readonly<{ origin: string; summary: string; permissions: ReadonlyArray<{ name: string; state: 'BLOCKED' }> }>;
export interface AxonBrowserPlugin {
  open(options?: { url?: string }): Promise<{ opened: boolean; url: string }>;
  navigate(options: { url: string }): Promise<NativeBrowserState>;
  back(): Promise<NativeBrowserState>;
  forward(): Promise<NativeBrowserState>;
  reload(): Promise<NativeBrowserState>;
  stop(): Promise<NativeBrowserState>;
  newTab(options?: { url?: string }): Promise<NativeBrowserState>;
  switchTab(options: { index: number }): Promise<NativeBrowserState>;
  closeTab(options: { index: number }): Promise<NativeBrowserState>;
  getState(): Promise<NativeBrowserState>;
  getPageText(): Promise<{ text: string }>;
  findInPage(options: { text: string }): Promise<void>;
  zoomBy(options: { delta: number }): Promise<void>;
  setDesktopSite(options: { enabled: boolean }): Promise<NativeBrowserState>;
  addBookmark(options: { title: string; url: string }): Promise<void>;
  editBookmark(options: { index: number; title: string; url: string }): Promise<void>;
  removeBookmark(options: { index: number }): Promise<void>;
  createBookmarkFolder(options: { name: string }): Promise<void>;
  moveBookmark(options: { index: number; folder: string }): Promise<void>;
  listBookmarks(): Promise<{ items: BrowserSavedItem[]; folders: string[] }>;
  searchHistory(options?: { query?: string }): Promise<{ items: BrowserSavedItem[] }>;
  clearHistory(): Promise<void>;
  clearHistoryBySite(options: { host: string }): Promise<void>;
  addToReadingList(options: { title: string; url: string }): Promise<void>;
  removeReadingListItem(options: { index: number }): Promise<void>;
  openReadingListItem(options: { index: number }): Promise<NativeBrowserState>;
  markReadingListRead(options: { index: number; read: boolean }): Promise<void>;
  listReadingList(): Promise<{ items: BrowserSavedItem[] }>;
  listDownloads(): Promise<{ items: BrowserDownloadItem[] }>;
  openDownload(options: { id: string }): Promise<void>;
  shareDownload(options: { id: string }): Promise<void>;
  cancelDownload(options: { id: string }): Promise<void>;
  deleteDownload(options: { id: string }): Promise<void>;
  copyCurrentUrl(): Promise<void>;
  shareCurrentUrl(): Promise<void>;
  printPage(): Promise<void>;
  savePagePdf(): Promise<void>;
  getSecurityDetails(): Promise<BrowserSecurityDetails>;
  getSitePermissions(): Promise<BrowserSitePermissionSummary>;
}
